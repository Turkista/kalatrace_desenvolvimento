"""
KALATRACE Robotics Observation Model

Represents a contextualized measurement
generated by a robotic sensor.

An Observation transforms raw sensor
data into structured information.
"""


from datetime import datetime, timezone
from typing import Any


class Observation:
    """
    Represents a robotic perception event.
    """


    def __init__(
        self,
        observation_id: str,
        robot_id: str,
        sensor_id: str,
        observation_type: str,
        value: Any,
        unit: str,
        confidence: float = None,
        location: str = None,
        context: dict = None
    ):

        self.observation_id = observation_id

        self.robot_id = robot_id

        self.sensor_id = sensor_id

        self.observation_type = observation_type

        self.value = value

        self.unit = unit

        self.confidence = confidence

        self.location = location

        self.context = context or {}

        self.created_at = datetime.now(
            timezone.utc
        )


    def to_dict(self):
        """
        Convert observation into
        structured data.
        """

        return {

            "observation_id":
                self.observation_id,

            "robot_id":
                self.robot_id,

            "sensor_id":
                self.sensor_id,

            "type":
                self.observation_type,

            "value":
                self.value,

            "unit":
                self.unit,

            "confidence":
                self.confidence,

            "location":
                self.location,

            "context":
                self.context,

            "created_at":
                self.created_at.isoformat()
        }