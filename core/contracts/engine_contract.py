"""
KALATRACE Core

Engine Contract

Defines the required behavior of processing engines
within the KALATRACE architecture.
"""

from __future__ import annotations

from abc import abstractmethod
from typing import Any

from core.contracts.lifecycle_contract import (
    LifecycleContract,
)

from core.metadata.component_metadata import (
    ComponentMetadata,
)

from core.runtime.runtime_context import (
    RuntimeContext,
)


class EngineContract(LifecycleContract):
    """
    Contract for KALATRACE engines.

    Engines are responsible for processing,
    reasoning, computation and specialized execution.
    """


    @property
    @abstractmethod
    def identifier(self) -> str:
        """
        Returns unique engine identifier.
        """
        ...


    @property
    @abstractmethod
    def metadata(self) -> ComponentMetadata:
        """
        Returns engine metadata information.
        """
        ...


    @abstractmethod
    def execute(
        self,
        context: RuntimeContext,
    ) -> Any:
        """
        Executes the engine operation.

        Parameters
        ----------
        context:
            Runtime execution context.

        Returns
        -------
        Any:
            Result generated by the engine.
        """
        ...


    @property
    def engine_type(self) -> str:
        """
        Returns the engine category.

        Default implementation.
        """

        return "generic"


    @property
    def dependencies(
        self,
    ) -> tuple[str, ...]:
        """
        Returns required dependencies.

        Default implementation.
        """

        return ()